import os
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch

import vps_manage
import vps_singbox

class SingboxTests(unittest.TestCase):
    def test_known_release_and_local_handshake(self):
        script=vps_singbox.BRIDGE_SCRIPT
        self.assertEqual(subprocess.run(['bash','-n'],input=script,text=True,capture_output=True).returncode,0)
        for part in ('sing-box-1.12.25-linux-', 'sha256sum -c --status', 'from logic.vpn_bridge import build_config, parse_link', "'127.0.0.1'", "'vpn_refresh'", 'mv -f --'):
            self.assertIn(part,script)
        self.assertNotIn('systemctl restart',script)
        self.assertEqual(vps_manage.command_script('setup_bridge'),script)

    def test_checksum_or_runtime_failure_never_replaces_binary(self):
        for failure in ('checksum','runtime','none'):
            with self.subTest(failure=failure), tempfile.TemporaryDirectory() as folder:
                t=Path(folder);root=t/'app';runtime=t/'runtime';conf=t/'config';bins=t/'bin';tmp=t/'temp'
                for p in (root/'logic',root/'.venv/bin',runtime,conf,bins,tmp):p.mkdir(parents=True,exist_ok=True)
                (root/'logic/vpn_bridge.py').write_text('placeholder')
                (root/'.venv/bin/python').write_text('placeholder');(root/'.venv/bin/python').chmod(0o755)
                (conf/'bot.env').write_text('SING_BOX_BIN=/opt/rakcrmp-black-runtime/sing-box\n')
                original=runtime/'sing-box';original.write_text('old-binary');original.chmod(0o755)
                def stub(name,body):
                    p=bins/name;p.write_text('#!/bin/sh\n'+body+'\n');p.chmod(0o755)
                stub('id','echo 0');stub('uname','echo x86_64');stub('flock','exit 0')
                stub('curl','while [ "$1" != "-o" ]; do shift; done; : > "$2"; exit 0')
                stub('sha256sum', 'exit 1' if failure=='checksum' else 'exit 0')
                stub('tar','printf new-binary');stub('chown','exit 0')
                stub('runuser', 'exit 1' if failure=='runtime' else 'exit 0')
                stub('systemctl','exit 0')
                script=vps_singbox.BRIDGE_SCRIPT.replace('/opt/rakcrmp-black-runtime',str(runtime)).replace('/opt/rakcrmp-black',str(root)).replace('/etc/rakcrmp-black',str(conf))
                # Config is generated by the real installer and contains the actual path.
                (conf/'bot.env').write_text('SING_BOX_BIN='+str(runtime)+'/sing-box\n')
                env=os.environ.copy();env.update(PATH=str(bins)+':'+env['PATH'],TMPDIR=str(tmp))
                result=subprocess.run(['bash'],input=script,text=True,capture_output=True,env=env,timeout=15)
                expected={'checksum':45,'runtime':46,'none':0}[failure]
                self.assertEqual(result.returncode,expected,result.stderr)
                self.assertEqual(original.read_text(),'new-binary' if failure=='none' else 'old-binary')
